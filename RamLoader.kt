package com.example.stlinkflasher

/**
 * Programs flash by running a tiny Thumb routine from SRAM instead of pushing every word
 * through the debug port with PG set.
 *
 * The routine (tools/flashloader.S) programs halfwords from an SRAM buffer, polls BSY,
 * checks PGERR/WRPRTERR per halfword, kicks the independent watchdog, and ends in BKPT with
 * R0 = 0 on success or the failing FLASH_SR value. This class loads it, fills the buffer in
 * [BUF_SIZE] blocks, runs it with interrupts masked and reads the result.
 *
 * SRAM layout, kept inside the 6 KB of the smallest F103:
 *   0x20000000  loader code (76 bytes)
 *   0x20000100  data buffer (4 KB)
 *   0x20001200  initial stack pointer (the loader doesn't use the stack)
 *
 * The flash must already be unlocked and the target pages erased by the caller.
 */
class RamLoader(private val link: StLink) {

    companion object {
        const val CODE_ADDR = 0x20000000L
        const val BUF_ADDR = 0x20000100L
        const val BUF_SIZE = 4096
        const val STACK_TOP = 0x20001200L

        private const val FLASH_SR = 0x4002200CL
        private const val SR_CLEAR_FLAGS = 0x34 // EOP | WRPRTERR | PGERR (write 1 to clear)
        private const val SR_WRPRTERR = 0x10
        private const val RUN_TIMEOUT_MS = 3000L

        // Generated by tools/build_loader.py from tools/flashloader.S and checked by
        // tools/test_flashloader.py. Regenerate both if the assembly changes.
        private val CODE_HALFWORDS = intArrayOf(
            0x2340, 0x061B, 0x2422, 0x0324, 0x191B, 0x2401, 0x611C, 0x26AA,
            0x0237, 0x433E, 0x2740, 0x063F, 0x2403, 0x0324, 0x193F, 0x2A00,
            0xD00C, 0x880C, 0x8004, 0x603E, 0x68DC, 0x0865, 0xD2FC, 0x2514,
            0x422C, 0xD107, 0x3002, 0x3102, 0x3A02, 0xE7F0, 0x2400, 0x611C,
            0x2000, 0xBE00, 0x2500, 0x611D, 0x4620, 0xBE00,
        )

        private val CODE: ByteArray = ByteArray(CODE_HALFWORDS.size * 2).also { b ->
            CODE_HALFWORDS.forEachIndexed { i, h ->
                b[2 * i] = (h and 0xFF).toByte()
                b[2 * i + 1] = (h shr 8).toByte()
            }
        }
    }

    private fun install() {
        link.halt()
        link.writeMem32(CODE_ADDR, CODE)
        if (!link.readMem32(CODE_ADDR, CODE.size).contentEquals(CODE)) {
            throw StLinkException("Flash loader did not land in RAM intact.")
        }
    }

    /** Runs the loader once and returns its R0. Throws on USB trouble or if it never halts. */
    private fun run(dst: Long, len: Int): Int {
        link.writeCoreReg(0, dst.toInt())
        link.writeCoreReg(1, BUF_ADDR.toInt())
        link.writeCoreReg(2, len)
        link.writeCoreReg(13, STACK_TOP.toInt())
        link.writeCoreReg(15, CODE_ADDR.toInt())
        link.writeCoreReg(16, 0x01000000) // xPSR with the Thumb bit set
        link.runMasked()
        if (!link.waitHalted(RUN_TIMEOUT_MS)) {
            link.halt()
            throw StLinkException("Flash loader did not finish (timeout).")
        }
        val r0 = link.readCoreReg(0)
        link.halt() // also drops the interrupt mask
        return r0
    }

    /**
     * Installs the loader and runs it on zero bytes. True means the whole path works on this
     * probe and target (core register access, SRAM execution, BKPT halt); false means the
     * caller should fall back to direct programming.
     */
    fun selfTest(): Boolean = try {
        selfTestOrThrow()
        true
    } catch (e: StLinkException) {
        runCatching { link.halt() }
        false
    }

    /** Same as [selfTest] but says why it failed. Doesn't touch flash (length 0, flash may stay locked). */
    fun selfTestOrThrow() {
        install()
        val r0 = run(Stm32F1.FLASH_BASE, 0)
        if (r0 != 0) throw StLinkException("Loader halted but returned 0x%X instead of 0.".format(r0))
    }

    /** [data] must be a multiple of 4 bytes. Blocks that are entirely 0xFF are skipped (already erased). */
    fun program(dst: Long, data: ByteArray, onProgress: (Int) -> Unit) {
        require(data.size % 4 == 0) { "data must be word-aligned" }
        var off = 0
        while (off < data.size) {
            val n = minOf(BUF_SIZE, data.size - off)
            val block = data.copyOfRange(off, off + n)
            if (!block.all { it == 0xFF.toByte() }) {
                link.writeMem32(BUF_ADDR, block)
                val r0 = run(dst + off, n)
                if (r0 != 0) throw failure(dst + off, r0)
            }
            off += n
            onProgress(off * 100 / data.size)
        }
    }

    private fun failure(blockAddr: Long, sr: Int): StLinkException {
        runCatching { link.writeReg32(FLASH_SR, SR_CLEAR_FLAGS) }
        return if ((sr and SR_WRPRTERR) != 0) {
            StLinkException("Flash is write-protected in the block at 0x%08X.".format(blockAddr))
        } else {
            StLinkException("Flash programming error in the block at 0x%08X (page not erased?).".format(blockAddr))
        }
    }
}
